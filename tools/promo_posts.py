def challenge(day: int) -> str:
    r = random.Random(day * 7919)
    kind = r.choice(["form", "score", "time", "virus", "anom", "fall"])
    if kind == "form":
        f = FORMS[r.choice([5, 6, 7, 8, 9, 10, 11])][1]
        return f"вывести {f} за одну партию"
    if kind == "score":
        return f"набрать {r.choice([600, 700, 800, 900, 1000, 1200, 1500])} очков в классике"
    if kind == "time":
        return f"продержаться {r.choice([3, 4, 5, 6])} минуты без переполнения"
    if kind == "virus":
        return f"вывести {r.choice(['Грипп', 'Бешенство', 'Эболу'])} в вирусной ветке"
    if kind == "anom":
        return r.choice(["раздавить двух паразитов", "растворить три гнили", "разбить куклу до её смеха",
                         "залатать утечку и не потерять ни одного мутанта", "пройти проверку, не шелохнувшись"])
    return f"набрать {r.choice([500, 700, 1000])} очков в режиме «Падение»"


def build():
    themes = (
        [("form", f) for f in FORMS] * 5 + [("anom", a) for a in ANOMS] * 6 + [("event", e) for e in EVENTS] * 5
        + [("trial", t) for t in TRIALS] * 6 + [("mode", m) for m in MODES] * 5 + [("fact", f) for f in FACTS] * 3
    )
    rnd.shuffle(themes)
    themes = (themes * 2)[:365]
    posts = []
    for d in range(365):
        kind, item = themes[d]
        date = (START + datetime.timedelta(days=d)).isoformat()
        hook, tip, cta, em = HOOKS[d % len(HOOKS)], TIPS[(d // len(HOOKS) + d * 3) % len(TIPS)], CTAS[(d * 3 + d // 10) % len(CTAS)], EMO[(d + d // 10) % len(EMO)]
        ch = challenge(d)
        art = {"layout": d % 4, "palette": (d * 5) % 8, "day": d + 1}
        if d == 0:
            title = "«Мутация» — хоррор-головоломка прямо в браузере"
            body = body_plain = ("Бросайте мутантов в банку с формалином. Две одинаковые твари сливаются в новую форму — от Капли до Матки, "
                                 "а каждая новая форма встречает вас скримером. 15 мутантов, вирусы, аномалии, 5 испытаний и дневной забег.")
            art.update(kind="intro", form=14, headline="МУТАЦИЯ", sub="Сливайте мутантов в банке с формалином, пока она не лопнула")
        elif kind == "form":
            fid, name, desc, lore = item
            title = f"{name}" if d % 2 else f"Мутант дня: {name}"
            body = f"{desc}\n\n<i>Журнал лаборанта: «{lore}»</i>"
            body_plain = f"{desc}\n\nЖурнал лаборанта: «{lore}»"
            art.update(kind="form", form=fid, headline=name, sub=desc)
        elif kind == "anom":
            aid, name, desc = item
            title = f"Аномалия: {name}"
            body = body_plain = desc
            art.update(kind="anom", anom=aid, headline=name, sub=desc)
        elif kind == "event":
            name, desc, fid = item
            title = name
            body = body_plain = desc
            art.update(kind="form", form=fid, headline=name, sub=desc)
        elif kind == "trial":
            name, desc, tid = item
            title = f"Испытание: {name}"
            body = body_plain = desc + " До трёх звёзд за уровень."
            art.update(kind="trial", trial=tid, form=[7, 16, 13, 12, 18][[t[2] for t in TRIALS].index(tid)], headline=name, sub=desc)
        elif kind == "mode":
            name, desc = item
            title = name
            body = body_plain = desc
            art.update(kind="form", form=[14, 4, 7, 2, 10, 11][[m[0] for m in MODES].index(name)], headline=name, sub=desc)
        else:
            title = "Факт о настоящих вирусах"
            body = body_plain = item
            art.update(kind="form", form=[15, 15, 16, 17, 18, 19, 16, 17, 15, 19][FACTS.index(item)], headline="Это правда", sub=item)
        art["challenge"] = ch
        tg = (f"<b>{em} {title}</b>\n<i>Смена лаборанта №{d + 1}</i>\n\n{hook}\n\n{body}\n\n"
              f"🎯 <b>Задание дня:</b> {ch}.\n💡 {tip}\n\n<a href=\"{URL}\">{cta}</a>")
        mx = (f"{em} {title}\nСмена лаборанта №{d + 1}\n\n{hook}\n\n{body_plain}\n\n"
              f"🎯 Задание дня: {ch}.\n💡 {tip}\n\n{cta.replace('▶️ ', '')}: {URL}")
        posts.append({"day": d + 1, "date": date, "theme": "intro" if d == 0 else kind, "image": f"{IMG}{d + 1:03d}.jpg",
                      "tg_html": tg, "max_text": mx, "art": art})
    texts = [p["tg_html"] for p in posts]
    assert len(set(texts)) == 365, "посты повторяются"
    out = {"game_url": URL, "start": START.isoformat(), "count": 365,
           "how_to_pick": "Возьмите запись с date = сегодняшняя дата по Москве. Если её нет (прошёл год) — запись с day = ((сегодня − start) mod 365) + 1.",
           "posts": posts}
    path = ROOT / "promo" / "daily" / "posts.json"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(out, ensure_ascii=False, indent=1), encoding="utf-8")
    print("постов:", len(posts), "уникальных текстов:", len(set(texts)), "→", path)


build()
